#!/bin/sh
# Writes a header that makes a program built for the host see Zoraya's signal
# numbers, which are musl's (the sysroot's <signal.h>). dash's mksignames runs
# on the host (ADR-0109 item 6) and would otherwise print the host's numbering:
# on macOS SIGBUS is 10 and SIGUSR1 30, on Zoraya 7 and 10.
#
# Usage: target-signals.sh HOSTCC ZCC > header. The header includes the host's
# <signal.h>, then removes every SIG name the host defines and defines the
# target's. SIGRTMIN and SIGRTMAX are calls in musl's header, so they are left
# undefined, as are the stack sizes.
set -eu
hostcc=$1
zcc=$2
host=$(printf '#include <signal.h>\n' | $hostcc -E -dM -x c - | awk '$2 ~ /^SIG[A-Z0-9]+$/ { print $2 }' | sort -u)
target=$(printf '#include <signal.h>\n' | $zcc -D_GNU_SOURCE -E -dM -x c - |
    awk '$2 ~ /^SIG[A-Z0-9]+$/ && $2 !~ /STKSZ$/ && $2 != "SIGRTMIN" && $2 != "SIGRTMAX" { print $2, $3 }' | sort)
nsig=$(printf '#include <signal.h>\n' | $zcc -D_GNU_SOURCE -E -dM -x c - | awk '$2 == "_NSIG" { print $3 }')
[ -n "$nsig" ] || { echo "target-signals.sh: no _NSIG in the sysroot's <signal.h>" >&2; exit 1; }
echo "/* Generated by ports/target-signals.sh: Zoraya's signal numbers for host tools. */"
echo "#include <signal.h>"
for s in $host SIGRTMIN SIGRTMAX NSIG; do echo "#undef $s"; done
echo "#define NSIG $nsig"
echo "$target" | while read -r name value; do echo "#define $name $value"; done
