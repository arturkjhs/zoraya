#!/bin/sh
# Builds the thread tests of musl's libc-test (unpacked by `make -f
# ports/Makefile suites`) with tools/zcc against libc.a, into OUT, and writes
# OUT/list, the names that were built, and OUT/script, a runner script for
# tools/test-runner (ADR-0309 item 1). A test left out is named, with its
# reason, in tests/libc-test/threads-excluded.txt; an excluded name that is
# not a test of the source, or a test that fails to compile, is an error.
#
#   build.sh SRC OUT
set -eu
src=$1
out=$2
here=$(dirname "$0")
excluded=$here/threads-excluded.txt
mkdir -p "$out/bin"
: > "$out/list"
names() {
    for f in "$src"/src/functional/pthread_*.c "$src"/src/functional/sem_init.c "$src"/src/functional/tls_*.c \
        "$src"/src/regression/pthread_*.c "$src"/src/regression/pthread-*.c "$src"/src/regression/sem_*.c; do
        [ -f "$f" ] && echo "${f#"$src"/src/}" | sed 's/\.c$//'
    done
}
for n in $(sed -e 's/#.*//' "$excluded" | awk 'NF { print $1 }'); do
    case $n in sqlite/*) continue ;; esac
    [ -f "$src/src/$n.c" ] || { echo "libc-test: $n is excluded but is not a test of this source" >&2; exit 1; }
done
for n in $(names); do
    if awk -v n="$n" '$1 == n { f = 1 } END { exit !f }' "$here/threads-excluded.txt"; then
        continue
    fi
    base=$(echo "$n" | sed 's|.*/||')
    # The first listed name wins when a functional and a regression test share one.
    [ -f "$out/bin/$base" ] && continue
    tools/zcc -O2 -w -I"$src/src/common" -o "$out/bin/$base" "$src/src/$n.c" "$src/src/common/print.c" ||
        { echo "libc-test: $n does not build" >&2; exit 1; }
    echo "$base" >> "$out/list"
done
{
    printf '%s\n' "# Generated by tests/libc-test/build.sh: musl's libc-test thread tests, each by posixrun."
    printf '%s\n' "! panicked" "! ZORAYA-PANIC" '< \r\n~> '
    for b in $(cat "$out/list"); do
        printf '%s\n' "> posixrun /bin/lct/$b\\r" "< posixrun: exit 0" '< \r\n~> '
    done
    printf '%s\n' '> poweroff\r'
} > "$out/script"
echo "libc-test: $(wc -l < "$out/list" | tr -d ' ') tests built"
