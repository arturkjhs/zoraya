#!/bin/sh
# Writes the runner script of make test-cxx-gtest (TASK-30) to standard
# output: each GoogleTest test program of LIST (make -f ports/Makefile gtest)
# run by gtrun (tests/cxx/gtrun.c) through the shell, expected to end with
# GoogleTest's summary and exit 0, or as tests/cxx/gtest-expect.txt says.
#
#   gtest.sh LIST
set -eu
list=$1
expect=$(dirname "$0")/gtest-expect.txt
printf '%s\n' "# Generated by tests/cxx/gtest.sh: GoogleTest's own tests, each by gtrun."
printf '%s\n' "! panicked" "! ZORAYA-PANIC" '< \r\n~> '
# A failed program is seen by its status: GoogleTest prints its list of
# failures after the summary, so a failing program ends the run at the
# runner's timeout (no pattern fits every program: gtest_stress_test fails on
# purpose and prints FAILED TESTS).
while read -r t; do
    line=$(grep -v '^#' "$expect" | awk -F'|' -v t="$t" '$1 == t { print; exit }')
    args=
    status=0
    last='[  PASSED  ]'
    if [ -n "$line" ]; then
        args=$(printf "%s\n" "$line" | cut -d'|' -f2)
        status=$(printf "%s\n" "$line" | cut -d'|' -f3)
        last=$(printf "%s\n" "$line" | cut -d'|' -f4-)
    fi
    printf '> gtrun %s%s\\r\n' "$t" "${args:+ '$args'}"
    printf '< %s\n< \\r\\n~> \n> status\\r\n' "$last"
    if [ "$status" = 0 ]; then
        printf '< \\r\\nsucceeded (exit status 0)\n'
    else
        printf '< \\r\\nexit status %s\n' "$status"
    fi
    printf '< \\r\\n~> \n'
done < "$list"
printf '%s\n' '> poweroff\r'
