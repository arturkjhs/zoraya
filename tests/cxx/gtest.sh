#!/bin/sh
# Writes the runner script of make test-cxx-gtest (TASK-30) to standard
# output: each GoogleTest test program of LIST (make -f ports/Makefile gtest)
# run by posixrun in /work, expected to end with GoogleTest's summary and
# exit 0. tests/cxx/gtest-expect.txt gives a program's other ending (a line
# to wait for and the exit status) where GoogleTest's own CMake test expects
# one.
#
#   gtest.sh LIST
set -eu
list=$1
expect=$(dirname "$0")/gtest-expect.txt
printf '%s\n' "# Generated by tests/cxx/gtest.sh: GoogleTest's own tests, each by posixrun in /work."
printf '%s\n' "! panicked" "! ZORAYA-PANIC" '< \r\n~> '
while read -r t; do
    line=$(awk -v t="$t" '$1 == t { $1 = ""; sub(/^ /, ""); print; exit }' "$expect")
    printf '> posixrun -C /work /bin/gt/%s\\r\n' "$t"
    if [ -n "$line" ]; then
        status=${line%% *}
        text=${line#* }
        printf '< %s\n< posixrun: exit %s\n' "$text" "$status"
    else
        printf '< [  PASSED  ]\n< posixrun: exit 0\n'
    fi
    printf '< \\r\\n~> \n'
done < "$list"
printf '%s\n' '> poweroff\r'
