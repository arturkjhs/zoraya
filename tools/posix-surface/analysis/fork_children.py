"""X-2 input: what the children of fork-style and vfork-style clones do (strace, all runs).

For every clone, the child is classified by what it does itself:
  exec      - the child itself calls execve successfully (fork+exec shape, replaceable by a spawn)
  no-exec   - the child never execs and keeps running the parent's code (fork-without-exec shape)
For no-exec children, `spawns` counts those that create processes of their own (e.g. a pipeline subshell).
Pids are not reused within a run (pid_max 32768, checked), so a trace is parsed in two passes: the first collects
clone, execve and parent links (a child's lines can precede the parent's clone return), the second classifies.
Writes results/fork-children.md and results/fork-children.tsv.
"""
import sys, os, re, glob, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import runs as R

W = sys.argv[1]
RAW, RES = os.path.join(W, "raw", "strace"), os.path.join(W, "results")
M = R.Mapper(W)
LINE = re.compile(r"^(\d+)\s+(.*)$")
EXEC = re.compile(r'^execve\("([^"]*)", \["([^"]*)"')
RET = re.compile(r"= (-?\d+)(?: \w+)?(?: \(.*\))?$")

def kind(flags):
    if "CLONE_THREAD" in flags:
        return "thread"
    return "vfork" if "CLONE_VFORK" in flags else "fork"

rows = []   # (run, run kind, parent program, clone kind, class, spawns)
for f in sorted(glob.glob(os.path.join(RAW, "*.txt"))):
    fid = os.path.basename(f)[:-4]
    if fid.endswith("-check"):
        continue
    first_exec, execs, clones, parent = {}, collections.defaultdict(list), [], {}
    pend_exec, pend_clone = {}, {}
    for i, l in enumerate(open(f, errors="replace")):
        m = LINE.match(l.rstrip("\n"))
        if not m:
            continue
        pid, rest = int(m.group(1)), m.group(2)
        if rest.startswith("execve("):
            e = EXEC.match(rest)
            if "<unfinished" in rest:
                pend_exec[pid] = e and (e.group(1), e.group(2))
            elif e and rest.endswith("= 0"):
                execs[pid].append((i, e.group(1), e.group(2)))
        elif rest.startswith("<... execve resumed>") and rest.endswith("= 0") and pend_exec.get(pid):
            execs[pid].append((i,) + pend_exec.pop(pid))
        elif rest.startswith(("clone(", "clone3(")):
            if "<unfinished" in rest:
                pend_clone[pid] = rest
            else:
                r = RET.search(rest)
                if r and int(r.group(1)) > 0:
                    clones.append((i, pid, int(r.group(1)), kind(rest)))
        elif rest.startswith(("<... clone resumed>", "<... clone3 resumed>")) and pid in pend_clone:
            r = RET.search(rest)
            if r and int(r.group(1)) > 0:
                clones.append((i, pid, int(r.group(1)), kind(pend_clone[pid] + rest)))
            pend_clone.pop(pid, None)
    for i, p, c, k in clones:
        parent[c] = (p, i)
    has_children = {p for i, p, c, k in clones if k != "thread"}

    def image(pid, at):
        """program running in pid at line `at`"""
        ex = [e for e in execs.get(pid, []) if e[0] <= at]
        if ex:
            return M.program(ex[-1][2], M.resolve(ex[-1][1]))
        if pid in parent:
            return image(*parent[pid])
        return "?"

    for i, p, c, k in clones:
        if k == "thread":
            continue
        cls = "exec" if execs.get(c) else "no-exec"
        rows.append((fid, R.run_kind(fid), image(p, i), k, cls, cls == "no-exec" and c in has_children))

agg = collections.Counter((r[1], r[2], r[3], r[4]) for r in rows)
spw = collections.Counter((r[1], r[2], r[3]) for r in rows if r[5])
with open(os.path.join(RES, "fork-children.tsv"), "w") as o:
    o.write("run\tkind\tparent\tclone\tchild\tnoexec_child_spawns\n")
    per = collections.Counter(rows)
    for r, n in sorted(per.items()):
        o.write("\t".join(map(str, r)) + f"\t{n}\n")

md = ["<!-- generated by tools/posix-surface/analysis/fork_children.py; do not edit -->", "",
      "Children of fork-style and vfork-style clones, all runs except `*-check` (strace). `exec`: the child itself "
      "execs; `no-exec`: it keeps running the parent's code; `of which spawn`: no-exec children that create "
      "processes themselves.", "",
      "| Run kind | Parent | Clone | exec | no-exec | of which spawn |", "|---|---|---|---|---|---|"]
for key in sorted({(a, b, c) for a, b, c, d in agg}):
    md.append(f"| {key[0]} | {key[1]} | {key[2]} | {agg[key + ('exec',)]} | {agg[key + ('no-exec',)]} | {spw[key]} |")
open(os.path.join(RES, "fork-children.md"), "w").write("\n".join(md) + "\n")
