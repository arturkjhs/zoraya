"""X-3 input: signals actually delivered during the workloads, processes killed by a signal, and system calls
interrupted by a signal (EINTR / ERESTART*), from the strace logs of all runs except `*-check`.
Writes results/signals-delivered.md.
"""
import sys, os, re, glob, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import runs as R

W = sys.argv[1]
RAW, RES = os.path.join(W, "raw", "strace"), os.path.join(W, "results")
SIG = re.compile(r"^\d+\s+--- (SIG\w+) \{si_signo=\w+, si_code=(\w+)")
KILLED = re.compile(r"^\d+\s+\+\+\+ killed by (SIG\w+)")
INTR = re.compile(r"^\d+\s+(?:<\.\.\. )?(\w+)(?:\(| resumed>).*= (?:\? (ERESTART\w+)|-1 (EINTR))")

sig, killed, intr = collections.Counter(), collections.Counter(), collections.Counter()
for f in sorted(glob.glob(os.path.join(RAW, "*.txt"))):
    fid = os.path.basename(f)[:-4]
    if fid.endswith("-check"):
        continue
    k = R.run_kind(fid)
    for l in open(f, errors="replace"):
        if "---" in l and (m := SIG.match(l)):
            sig[(k, fid, m.group(1), m.group(2))] += 1
        elif "+++" in l and (m := KILLED.match(l)):
            killed[(k, fid, m.group(1))] += 1
        elif ("ERESTART" in l or "EINTR" in l) and (m := INTR.match(l)):
            intr[(k, fid, m.group(1), m.group(2) or m.group(3))] += 1

md = ["<!-- generated by tools/posix-surface/analysis/signals_delivered.py; do not edit -->", "",
      "strace, all runs except `*-check`. `si_code` tells how the signal was raised: `CLD_*` by the kernel for a "
      "child state change, `SI_KERNEL` by the tty driver (Ctrl-C), `SI_TKILL` by `raise`/`tkill`, `SI_USER` by "
      "`kill`.", "",
      "### Signals delivered", "", "| Run kind | Run | Signal | si_code | Count |", "|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} | {n} |" for (a, b, c, d), n in sorted(sig.items())]
tot = collections.Counter()
for (a, b, c, d), n in sig.items():
    tot[(a, c, d)] += n
md += ["", "Totals by run kind:", ""] + [f"- {a}: {c} ({d}) {n}" for (a, c, d), n in sorted(tot.items())]
md += ["", "### Processes killed by a signal", "", "| Run kind | Run | Signal | Count |", "|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {n} |" for (a, b, c), n in sorted(killed.items())] or ["| — | — | — | 0 |"]
md += ["", "### System calls interrupted by a signal", "", "| Run kind | Run | Syscall | Result | Count |",
       "|---|---|---|---|---|"]
md += [f"| {a} | {b} | {c} | {d} | {n} |" for (a, b, c, d), n in sorted(intr.items())] or ["| — | — | — | — | 0 |"]
open(os.path.join(RES, "signals-delivered.md"), "w").write("\n".join(md) + "\n")
