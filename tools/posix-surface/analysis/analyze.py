    w.writerow(["symbol", "category", "programs", "static", "dynamic", "tier"])
    for s in sorted(syms):
        progs = sorted({R.base(p).split("-T")[0].replace("+libs", "") for p in static[s]} |
                       {R.base(p) for p in dyn_by_sym[s]})
        dyn = ";".join(f"{p}[{','.join(sorted(v))}]" for p, v in sorted(dyn_by_sym[s].items()))
        w.writerow([s, cat[s], ";".join(progs), ";".join(sorted(static[s])), dyn, sym_tier(s)])

