"""Turn raw static/dynamic/strace data into the published tables.

Usage: analyze.py <work-dir>   (reads <work>/results, <work>/raw; writes into <work>/results)

Outputs
  libc-surface.csv      symbol,category,programs,static,dynamic,tier
  syscall-surface.csv   syscall,programs,call_count_per_workload,notable_args
  summary-tables.md     every count quoted in docs/research/task-02/posix-surface.md
  dynamic-programs.tsv  every (run, kind, program, symbol) dynamic hit after attribution
  strace-patterns.tsv   per (tier, program, syscall, pattern) counts for the conflict-critical syscalls
  leaks.tsv             executions of binaries outside the measured sets
  symbol-headers.tsv    symbol -> musl header -> category
"""
