# ------------------------------------------------------------------ strace
LINE = re.compile(r"^(\d+)\s+(.*)$")
CALL = re.compile(r"^([a-z0-9_]+)\((.*)\)\s+=\s+(-?\d+|\?|0x[0-9a-f]+)(.*)$")
UNF = re.compile(r"^([a-z0-9_]+)\((.*?)\s*<unfinished \.\.\.>$")
RESU = re.compile(r"^<\.\.\. ([a-z0-9_]+) resumed>(.*)\)\s+=\s+(-?\d+|\?|0x[0-9a-f]+)(.*)$")

def fa(a):
    return a.split(",", 1)[0].strip()

def patterns(name, args, ret):
    out = []
    if name in ("clone", "clone3"):
        m = re.search(r"flags=([A-Z0-9_|]+)", args)
        f = m.group(1) if m else ""
        out.append(("kind", "thread" if "CLONE_THREAD" in f else ("vfork" if "CLONE_VFORK" in f else "fork")))
        out.append(("flags", f or "?"))
    elif name in ("openat", "open", "execve", "faccessat", "faccessat2", "newfstatat", "readlinkat",
                  "unlinkat", "mkdirat", "renameat2", "fchmodat", "statx", "chdir", "linkat", "symlinkat"):
        d = fa(args) if name not in ("execve", "chdir", "open") else "AT_FDCWD"
        m = re.search(r'"([^"]*)"', args)
        p = m.group(1) if m else ""
        out.append(("path", "dirfd" if d not in ("AT_FDCWD",) else ("abs" if p.startswith("/") else "rel")))
        for pre in ("/tmp", "/dev", "/proc", "/etc", "/usr", "/lib", "/bin", "/sys"):
            if p == pre or p.startswith(pre + "/"):
                out.append(("prefix", pre))
        if name in ("openat", "open"):
            m = re.search(r'",\s*([A-Z0-9_|]+)', args)
            out.append(("flags", m.group(1) if m else "?"))
        if name == "execve":
            out.append(("result", "ok" if ret == "0" else "fail"))
    elif name == "fcntl":
        parts = [x.strip() for x in args.split(",")]
        if len(parts) > 1:
            out.append(("cmd", parts[1]))
    elif name == "ioctl":
        parts = [x.strip() for x in args.split(",")]
        if len(parts) > 1:
            out.append(("req", parts[1]))
    elif name == "rt_sigaction":
        m = re.search(r"\{sa_handler=([A-Za-z0-9_]+)", args)
        h = m.group(1) if m else "query"
        out.append(("sig", f"{fa(args)}:{'handler' if h.startswith('0x') else h}"))
    elif name == "mmap":
        parts = [x.strip() for x in args.split(",")]
        if len(parts) > 3:
            out.append(("prot/flags", f"{parts[2]}/{parts[3]}"))
    elif name in ("wait4", "waitid"):
        parts = [x.strip() for x in args.split(",")]
        if len(parts) > 2:
            out.append(("opts", parts[2]))
    elif name in ("kill", "tgkill", "tkill"):
        out.append(("sig", args.split(",")[-1].strip()))
    elif name == "rt_sigprocmask":
        out.append(("how", fa(args)))
    elif name in ("setpgid", "setsid", "getpgid", "getsid", "setuid", "setgid", "umask", "fchmod",
                  "fchown", "getuid", "geteuid", "getgid", "getegid", "getgroups"):
        out.append(("called", name))
    return out

SETSDIR = os.path.join(W, "sets") + "/"
absexec = collections.Counter()
sc_count = collections.defaultdict(collections.Counter)
sc_progs = collections.defaultdict(set)
sc_pat = collections.defaultdict(collections.Counter)           # syscall -> "k=v" -> count (core runs)
prog_pat = collections.Counter()                                # (tier, program, syscall, k=v)
tier_sc = collections.defaultdict(set)
leaks = collections.Counter()
def parse_strace(path):
    """yield (lineno, pid, name, args, ret) with unfinished/resumed pairs joined"""
    pending = {}
    for i, raw in enumerate(open(path, errors="replace")):
        m = LINE.match(raw.rstrip("\n"))
        if not m:
            continue
        pid, rest = m.groups()
        if rest.startswith(("+++", "---")):
            continue
        u = UNF.match(rest)
        if u:
            pending[pid] = (i, u.group(1), u.group(2))
            continue
        r = RESU.match(rest)
        if r:
            i0, nm0, a0 = pending.pop(pid, (i, r.group(1), ""))
            yield i0, pid, r.group(1), a0 + r.group(2), r.group(3)
            continue
        c = CALL.match(rest)
        if c:
            yield i, pid, c.group(1), c.group(2), c.group(3)

for f in sorted(glob.glob(os.path.join(RAW, "strace", "*.txt"))):
    fid = os.path.basename(f)[:-4]
    kind, tier = R.run_kind(fid), R.tier_of_run(fid)
    events = list(parse_strace(f))
    # pass 1: exec events per pid and parent links. A vfork child's syscalls are logged before the parent's
    # clone returns, so attribution must look at the whole trace, not stream it.
    execs = collections.defaultdict(list)    # pid -> [(lineno, program)]
    parent = {}                              # child -> (parent pid, lineno of the clone call)
    for i, pid, name, args, ret in events:
        if name == "execve" and ret == "0":
            pm = re.search(r'^"([^"]*)",\s*\["([^"]*)"', args)
            if pm:
                path, arg0 = pm.groups()
                prog = M.program(arg0, M.resolve(path))
                if prog.startswith("built:") and not (path.startswith(".") or path.startswith(M.run)):
                    prog = "system:" + path
                execs[pid].append((i, prog))
                if not measured(prog) and not prog.startswith("built:"):
                    leaks[(fid, path)] += 1
        if name in ("clone", "clone3", "fork", "vfork") and ret.isdigit():
            parent[ret] = (pid, i)
    def prog_at(pid, i, depth=0, strict=False):
        best = None
        for li, p in execs.get(pid, ()):
            if li < i or (li == i and not strict):
                best = p
        if best is not None:
            return best
        if pid in parent and depth < 64:
            pp, li = parent[pid]
            return prog_at(pp, li, depth + 1)
        return "?"
    # pass 2: attribute
    for i, pid, name, args, ret in events:
        prog = prog_at(pid, i)
        if name == "execve":
            pm = re.search(r'^"([^"]*)"', args)
            caller = prog_at(pid, i, strict=True)   # the image that issued the execve
            if pm and caller != "?" and pm.group(1).startswith("/") and not pm.group(1).startswith(SETSDIR):
                # absolute path chosen by the program itself (PATH lookups resolve into the set directories);
                # caller "?" is the harness starting the workload and is not counted
                absexec[(tier, kind, R.base(caller) if measured(caller) else caller.split(":")[0], pm.group(1),
                         "ok" if ret == "0" else "fail")] += 1
        sc_count[name][fid] += 1
        sc_progs[name].add(prog)
        if kind == "core":
            tier_sc[tier].add(name)
        for k, v in patterns(name, args, ret):
            if kind == "core":
                sc_pat[name][f"{k}={v}"] += 1
            prog_pat[(tier, kind, R.base(prog) if measured(prog) else prog.split(":")[0], name, f"{k}={v}")] += 1

