def measured(p):
    return not p.startswith(("built:", "system:"))

# programs per tier (core runs, cumulative T0..T2; T3 alone)
core_progs = {}
for t in R.TIERS:
    tiers = R.tiers_upto(t)
    core_progs[t] = sorted({p for fid, k, tt, p, s in hits if k == "core" and tt in tiers and measured(p)})

def static_names(t, variant):
    """static 'programs' that make up tier t's upper bound. variant: full | min"""
    if t == "T3":
        return {"clang+libs", "ld.lld+libs"}
    names = set()
    for p in core_progs[t]:
        b = R.base(p)
        if b in ("toybox", "busybox"):
            names.add(f"{b}-{t}" if variant == "min" else b)
        else:
            names.add(b)
    return names

def upper(t, variant):
    out = set()
    for n in static_names(t, variant):
        out |= static_progs.get(n, set())
    return out

def lower(t, kinds=("core",)):
    tiers = R.tiers_upto(t)
    progs = set(core_progs[t])
    return {s for fid, k, tt, p, s in hits if k in kinds and tt in tiers and p in progs}

syms = set(static) | {h[4] for h in hits}
hdr = {s: C.header_of(s) for s in syms}
cat = {s: C.category(s, hdr[s]) for s in syms}
with open(os.path.join(RES, "symbol-headers.tsv"), "w") as f:
    for s in sorted(syms):
        f.write(f"{s}\t{hdr[s]}\t{cat[s]}\n")

UP = {t: {v: upper(t, v) for v in ("full", "min")} for t in R.TIERS}
