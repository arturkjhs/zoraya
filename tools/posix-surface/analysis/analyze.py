# Workloads ran the full toybox/busybox binaries. Their shared startup code (busybox setuid handling,
# long options; toybox root checks) is absent from the minimal builds, so a few observed symbols are not in the
# minimal import tables. The minimal upper bound is therefore min-imports ∪ observed, and the gap is reported.
MIN_GAP = {t: LO[t] - UP[t]["min"] for t in R.TIERS}
GAP_WHO = {t: sorted({f"{p}:{s}" for fid, k, tt, p, s in hits if k == "core" and tt in R.tiers_upto(t)
                      and s in MIN_GAP[t] and p in core_progs[t]}) for t in R.TIERS}
for t in R.TIERS:
    UP[t]["min"] = UP[t]["min"] | LO[t]

def sym_tier(s):
    for t in R.TIERS:
        if s in UP[t]["min"] or s in LO[t]:
            return t
    if any(s in UP[t]["full"] for t in R.TIERS):
        return "unused-applets"     # only in parts of toybox/busybox no workload executed
    return "comparison"

dyn_by_sym = collections.defaultdict(lambda: collections.defaultdict(set))
for fid, k, t, p, s in hits:
    if measured(p):
        dyn_by_sym[s][p].add(fid if k != "core" else R.wl_of(fid))
