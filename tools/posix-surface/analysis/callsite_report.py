"""M3 report: merge extracted call sites (results/callsites.tsv) with the per-site reviews (review/m3-*.tsv).

Usage: callsite_report.py <tools/posix-surface dir> <docs/research/task-02 dir>
Writes <docs>/callsites.csv (one row per site, final classification) and <tools>/results/callsite-tables.md.
A site without a review keeps its rule-based class and is marked source=rule.
"""
import csv, glob, os, sys, collections

T, D = sys.argv[1], sys.argv[2]
key = lambda r: (r["program"], r["file"], r["line"], r["api"])
rev = {}
for f in sorted(glob.glob(os.path.join(T, "review", "m3-*.tsv"))):
    for r in csv.DictReader(open(f), delimiter="\t"):
        rev[key(r)] = dict(r, _src=os.path.basename(f))
rows = list(csv.DictReader(open(os.path.join(T, "results", "callsites.tsv")), delimiter="\t"))
out = []
for r in rows:
    v = rev.get(key(r))
    if v:
        cls, eff, what, note, src = v["class"], v["effort_lines"], v["what"], v["note"], "review"
    else:
        cls, eff, what, note, src = r["rule_class"], r["rule_effort_lines"], "", r["rule_reason"], "rule"
    try:
        eff = int(float(eff or 0))
    except ValueError:
        eff = 0
    out.append(dict(program=r["program"], kind=r["kind"], tier=r["tier"], feature=r["feature"], api=r["api"],
                    file=r["file"], line=r["line"], function=r["function"], cls=cls.strip(), effort=eff,
                    what=what, note=note, code=r["code"], signals=r["signals"], source=src,
                    rule_class=r["rule_class"]))
with open(os.path.join(D, "callsites.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["program", "kind", "feature", "api", "file", "line", "function", "class", "effort_lines",
                "what", "note", "signals", "source", "rule_class"])
    for o in out:
        w.writerow([o["program"], o["kind"], o["feature"], o["api"], o["file"], o["line"], o["function"], o["cls"],
                    o["effort"], o["what"], o["note"], o["signals"], o["source"], o["rule_class"]])

CL = ["direct", "restructure", "emulate", "n/a"]
md = ["<!-- generated by tools/posix-surface/analysis/callsite_report.py; do not edit -->", ""]
src = collections.Counter(o["source"] for o in out)
md += [f"Sites: {len(out)} (reviewed: {src['review']}, rule only: {src['rule']}). "
       f"Rule class changed by review on {sum(1 for o in out if o['source']=='review' and o['cls']!=o['rule_class'])} sites.", ""]
md += ["### Sites by program and class (effort = sum of estimated lines)", "",
       "| Program | Kind | " + " | ".join(CL) + " | direct lines | restructure lines |", "|---|---|" + "---|" * (len(CL) + 2)]
progs = []
for o in out:
    if (o["program"], o["kind"]) not in progs:
        progs.append((o["program"], o["kind"]))
for p, k in progs:
    sub = [o for o in out if o["program"] == p]
    c = collections.Counter(o["cls"] for o in sub)
    md.append(f"| {p} | {k} | " + " | ".join(str(c.get(x, 0)) for x in CL) +
              f" | {sum(o['effort'] for o in sub if o['cls']=='direct')} | {sum(o['effort'] for o in sub if o['cls']=='restructure')} |")
md.append("")
feats = sorted({o["feature"] for o in out}, key=lambda s: (s.split()[0], s))
md += ["### Sites by feature and class (all programs; core programs in parentheses)", "",
       "| Feature | " + " | ".join(CL) + " |", "|---|" + "---|" * len(CL)]
for ft in feats:
    sub = [o for o in out if o["feature"] == ft]
    core = [o for o in sub if o["kind"] == "core"]
    md.append(f"| {ft} | " + " | ".join(f"{sum(o['cls']==x for o in sub)} ({sum(o['cls']==x for o in core)})" for x in CL) + " |")
md.append("")
# for features 1, 2, 4 (the X-2/X-3 critical ones): every restructure/emulate site, listed
for ft in [f for f in feats if f.startswith(("1 ", "2 ", "4 "))]:
    md += [f"### {ft}: restructure and emulate sites", "", "| Program | Site | Function | API | Class | Effort | What |", "|---|---|---|---|---|---|---|"]
    for o in out:
        if o["feature"] == ft and o["cls"] in ("restructure", "emulate"):
            md.append(f"| {o['program']} | `{o['file']}:{o['line']}` | {o['function']} | {o['api']} | {o['cls']} | "
                      f"{o['effort']} | {o['what'].replace('|', '/')} |")
    md.append("")
# signal sites by signal and class
md += ["### Signal sites by signal name (feature 2)", "", "| Signal | direct | restructure | emulate | n/a |", "|---|---|---|---|---|"]
sc = collections.defaultdict(collections.Counter)
for o in out:
    if o["feature"] == "2 signals":
        for s in (o["signals"].split(",") if o["signals"] else ["(none named)"]):
            sc[s][o["cls"]] += 1
for s, c in sorted(sc.items(), key=lambda kv: -sum(kv[1].values())):
    md.append(f"| {s} | " + " | ".join(str(c.get(x, 0)) for x in CL) + " |")
md.append("")
open(os.path.join(T, "results", "callsite-tables.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[:40]))
