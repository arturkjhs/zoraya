"""X-1 input: where absolute paths opened by core runs point (strace, `openat(AT_FDCWD, "/...")`, `*-check`
excluded). Paths are grouped by their first two components; the workload's own tree under the VM user's home
directory is folded into `<work>` (run directories, sources, the measured prefix incl. tcc's own include dir).
Writes results/path-prefixes.md.
"""
import sys, os, re, glob, collections
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import runs as R

W = sys.argv[1]
RAW, RES = os.path.join(W, "raw", "strace"), os.path.join(W, "results")
HOME = os.path.dirname(os.path.abspath(W))
OPEN = re.compile(r'^\d+\s+(?:openat\(AT_FDCWD|open\(), "(/[^"]*)"')

per = collections.defaultdict(collections.Counter)    # tier -> prefix -> count
for f in sorted(glob.glob(os.path.join(RAW, "*.txt"))):
    fid = os.path.basename(f)[:-4]
    if fid.endswith("-check") or R.run_kind(fid) != "core":
        continue
    t = R.tier_of_run(fid)
    for l in open(f, errors="replace"):
        if "open" in l and (m := OPEN.match(l)):
            p = m.group(1)
            if p.startswith(HOME + "/"):
                key = "<work>"
            else:
                parts = p.split("/")
                key = "/".join(parts[:3]) if len(parts) > 3 else p
                if key.startswith(("/tmp/", "/lib/")):
                    key = key[:key.index("/", 1)] + "/*"
            per[t][key] += 1

md = ["<!-- generated by tools/posix-surface/analysis/path_prefixes.py; do not edit -->", "",
      "Absolute paths opened in core runs (strace, all processes, `*-check` excluded), grouped by the first two path "
      "components. `<work>` is the workload's own tree under the VM user's home directory.", "",
      "| Prefix | " + " | ".join(R.TIERS) + " | All |", "|---|" + "---|" * (len(R.TIERS) + 1)]
allc = collections.Counter()
for t in per:
    allc.update(per[t])
for key, n in allc.most_common():
    md.append(f"| `{key}` | " + " | ".join(str(per[t][key]) for t in R.TIERS) + f" | {n} |")
open(os.path.join(RES, "path-prefixes.md"), "w").write("\n".join(md) + "\n")
