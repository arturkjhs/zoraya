"""TASK-02b M7 report: merge the extracted sites (results/par/callsites-par.tsv) with the per-site reviews
(review/m7-*.tsv: program, file, line, api, class, effort_lines, what, event_model, note).

Usage: callsite_par_report.py <tools/posix-surface dir> <docs/research/task-02b dir>
Writes <docs>/callsites.csv and <tools>/results/par/callsite-tables.md. Reviews are keyed by (program, file, line,
api) and apply to every feature the line carries. A site without a review is reported as `unreviewed`.
"""
import csv, glob, os, sys, collections

T, D = sys.argv[1], sys.argv[2]
key = lambda r: (r["program"], r["file"], r["line"], r["api"])
rev = {}
for f in sorted(glob.glob(os.path.join(T, "review", "m7-*.tsv"))):
    for r in csv.DictReader(open(f), delimiter="\t"):
        rev[key(r)] = r
rows = list(csv.DictReader(open(os.path.join(T, "results", "par", "callsites-par.tsv")), delimiter="\t"))
out = []
for r in rows:
    v = rev.get(key(r), {})
    try:
        eff = int(float(v.get("effort_lines") or 0))
    except ValueError:
        eff = 0
    out.append(dict(r, cls=(v.get("class") or "unreviewed").strip(), effort=eff, what=v.get("what", ""),
                    event=v.get("event_model", ""), note=v.get("note", "")))
os.makedirs(D, exist_ok=True)
with open(os.path.join(D, "callsites.csv"), "w", newline="") as f:
    w = csv.writer(f)
    w.writerow(["program", "feature", "api", "file", "line", "function", "class", "effort_lines", "what",
                "event_model", "note", "signals"])
    for o in out:
        w.writerow([o["program"], o["feature"], o["api"], o["file"], o["line"], o["function"], o["cls"], o["effort"],
                    o["what"], o["event"], o["note"], o["signals"]])

CL = ["direct", "restructure", "emulate", "n/a", "unreviewed"]
md = ["<!-- generated by tools/posix-surface/analysis/callsite_par_report.py; do not edit -->", "",
      f"Sites: {len(out)}; reviewed {sum(o['cls'] != 'unreviewed' for o in out)}. Classes, effort and the event-model "
      "mapping are estimates by reading code.", "",
      "### Sites by program, feature and class (effort = sum of estimated lines)", "",
      "| Program | Feature | " + " | ".join(CL) + " | direct lines | restructure lines |",
      "|---|---|" + "---|" * (len(CL) + 2)]
grp = collections.OrderedDict()
for o in out:
    grp.setdefault((o["program"], o["feature"]), []).append(o)
for (p, ft), os_ in sorted(grp.items()):
    c = collections.Counter(o["cls"] for o in os_)
    md.append(f"| {p} | {ft} | " + " | ".join(str(c[k]) for k in CL) +
              f" | {sum(o['effort'] for o in os_ if o['cls'] == 'direct')}"
              f" | {sum(o['effort'] for o in os_ if o['cls'] == 'restructure')} |")
for ft in sorted({o["feature"] for o in out}):
    md += ["", f"### {ft}", "", "| Program | Site | Function | API | Class | Effort | What | Event model (estimate) |",
           "|---|---|---|---|---|---|---|---|"]
    for o in out:
        if o["feature"] == ft:
            md.append(f"| {o['program']} | `{o['file']}:{o['line']}` | {o['function']} | {o['api']} | {o['cls']} | "
                      f"{o['effort']} | {o['what'].replace('|', '/')} | {o['event'].replace('|', '/')} |")
open(os.path.join(T, "results", "par", "callsite-tables.md"), "w").write("\n".join(md) + "\n")
