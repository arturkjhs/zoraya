"""W4: which autoconf checks of GNU hello come out differently with tcc than with the gcc baseline.

Pairs every `checking ...` line of config.log with its `result:` line, for the tcc configure run
(raw/W4-tcc-config.log) and the unmeasured gcc baseline (raw/W4-baseline-config.log). For checks whose result
differs, the first compiler/linker diagnostic logged under the tcc check is quoted.
Writes results/configure-checks.md.
"""
import sys, os, re, collections

W = sys.argv[1]
RAW, RES = os.path.join(W, "raw"), os.path.join(W, "results")
CHK = re.compile(r"^configure:\d+: checking (.*)$")
RES_ = re.compile(r"^configure:\d+: result: (.*)$")
DIAG = re.compile(r"(error|warning|undefined|cannot|not found)", re.I)

def parse(path):
    """-> ordered {(check, nth occurrence): (result, first diagnostic or '')}"""
    out, seen = {}, collections.Counter()
    cur, diag = None, ""
    for l in open(path, errors="replace"):
        l = l.rstrip("\n")
        m = CHK.match(l)
        if m:
            cur, diag = m.group(1).rstrip(". "), ""
            continue
        m = RES_.match(l)
        if m and cur is not None:
            seen[cur] += 1
            out[(cur, seen[cur])] = (m.group(1).strip(), diag)
            cur = None
        elif cur is not None and not diag and DIAG.search(l) and not l.startswith("configure:"):
            diag = l.strip()[:160]
    return out

tcc = parse(os.path.join(RAW, "W4-tcc-config.log"))
gcc = parse(os.path.join(RAW, "W4-baseline-config.log"))
diff = [(k, gcc[k][0], tcc[k]) for k in tcc if k in gcc and gcc[k][0] != tcc[k][0]]
only_tcc = [k for k in tcc if k not in gcc]
only_gcc = [k for k in gcc if k not in tcc]

md = ["<!-- generated by tools/posix-surface/analysis/configure_checks.py; do not edit -->", "",
      f"- checks with a result: tcc {len(tcc)}, gcc baseline {len(gcc)}, both {len(set(tcc) & set(gcc))}",
      f"- same check, different result: {len(diff)}",
      f"- only in the tcc run: {len(only_tcc)}; only in the gcc run: {len(only_gcc)}", "",
      "### Same check, different result", "", "| Check | gcc | tcc | First tcc diagnostic under the check |",
      "|---|---|---|---|"]
for (c, n), g, (t, d) in diff:
    md.append(f"| {c}{' (#%d)' % n if n > 1 else ''} | {g} | {t} | {d.replace('|', '/') or '—'} |")
for title, keys, src in (("Only in the tcc run", only_tcc, tcc), ("Only in the gcc run", only_gcc, gcc)):
    md += ["", f"### {title}", ""]
    md += [f"- {c}{' (#%d)' % n if n > 1 else ''}: {src[(c, n)][0]}" for c, n in keys] or ["- none"]
open(os.path.join(RES, "configure-checks.md"), "w").write("\n".join(md) + "\n")
