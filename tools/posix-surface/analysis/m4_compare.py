"""M4: compare the patched reruns (raw-m4/, results/m4/) against the baseline runs (raw/, results/).

Checks that behaviour is unchanged (exit statuses, workload outputs, generated config.h / config.mak) and
reports how the measured surface moved: which processes call vfork/system/posix_spawn, and the syscall mix.
Writes results/m4/m4-compare.md.
"""
import sys, os, re, glob, collections, filecmp
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import runs as R

W = sys.argv[1]
RES, RESM = os.path.join(W, "results"), os.path.join(W, "results", "m4")
RAW, RAWM = os.path.join(W, "raw"), os.path.join(W, "raw-m4")
RUN = os.path.join(W, "run")
M = R.Mapper(W)
m4bin = {os.path.realpath(os.path.join(W, "prefix", "m4", n)): n + "(patched)" for n in ("dash", "pdpmake")}
out = ["<!-- generated by tools/posix-surface/analysis/m4_compare.py; do not edit -->", ""]

def statuses(path):
    d = {}
    if os.path.exists(path):
        for l in open(path):
            p = l.rstrip("\n").split("\t")
            if len(p) == 3:
                d[p[0]] = p[2]
    return d

out += ["### Exit status, baseline vs patched", "", "| Run | Mode | Baseline | Patched |", "|---|---|---|---|"]
same = True
for mode in ("dynamic", "strace"):
    b, m = statuses(os.path.join(RES, f"{mode}-status.tsv")), statuses(os.path.join(RESM, f"{mode}-status.tsv"))
    for k, v in sorted(m.items()):
        base = b.get(k[2:], "?")
        same &= base == v
        out.append(f"| {k[2:]} | {mode} | {base} | {v} |")
out += ["", f"All exit statuses identical: **{same}**", ""]

out += ["### Workload outputs and generated files", ""]
def tailmatch(rid, pat, raw):
    p = os.path.join(raw, "dynamic", rid + ".log")
    return os.path.exists(p) and re.search(pat, open(p, errors="replace").read()) is not None
for rid, pat in (("W1-check", r"W1-OK"), ("W2-check-p", r"lua ok 42"), ("W2-check-g", r"lua ok 42"),
                 ("W4-check", r"Hello, world!")):
    out.append(f"- {rid}: baseline {'ok' if tailmatch(rid, pat, RAW) else 'MISSING'}, "
               f"patched {'ok' if tailmatch('M4' + rid, pat, RAWM) else 'MISSING'}")
for a, b in (("W4/src/config.h", "M4W4/src/config.h"), ("W4p/src/config.h", "M4W4p/src/config.h"),
             ("W1/src/config.mak", "M4W1/src/config.mak"), ("W1/src/config.h", "M4W1/src/config.h")):
    pa, pb = os.path.join(RUN, a), os.path.join(RUN, b)
    if os.path.exists(pa) and os.path.exists(pb):
        ta = open(pa).read().replace("/M4W", "/W"); tb = open(pb).read().replace("/M4W", "/W")
        out.append(f"- `{a}` identical after normalising the run directory: **{ta == tb}**")
    else:
        out.append(f"- `{a}`: missing ({os.path.exists(pa)}, {os.path.exists(pb)})")
out.append("")

def proc_calls(raw, prog_names, syms):
    """count processes of the given programs (by executable) that called each symbol at least once"""
    c = collections.Counter()
    for fid, pid, a0, exe, sym in R.load_hits_pid(raw):
        if sym not in syms:
            continue
        name = m4bin.get(exe) or M.program(a0, exe)
        wl = R.wl_of(fid.replace("M4", ""))
        if R.base(name) in prog_names and wl in RERUN:
            c[(wl, name, sym)] += 1
    return c

SY = {"vfork", "fork", "posix_spawn", "posix_spawnp", "system", "waitpid"}
RERUN = {"W1", "W2", "W4"}   # only these workloads were rerun with patched binaries
cb = proc_calls(RAW, {"dash", "pdpmake"}, SY)
cm = proc_calls(RAWM, {"dash(patched)", "pdpmake(patched)"}, SY)
out += ["### Processes calling process-creation functions (dynamic interposer, one count per process image)", "",
        "A process image is counted once per symbol however often it calls it (first-hit logging), so these are",
        "process counts, not call counts.", "",
        "| Workload | Program | Symbol | Baseline processes | Patched processes |", "|---|---|---|---|---|"]
keys = sorted({(w, n.replace("(patched)", ""), s) for (w, n, s) in list(cb) + list(cm)})
for w, n, s in keys:
    out.append(f"| {w} | {n} | {s} | {cb.get((w, n, s), 0)} | {cm.get((w, n + '(patched)', s), 0)} |")
out.append("")

def syscount(raw, names):
    c = collections.Counter()
    for f in glob.glob(os.path.join(raw, "strace", "*.txt")):
        wl = R.wl_of(os.path.basename(f)[:-4].replace("M4", ""))
        for line in open(f, errors="replace"):
            m = re.match(r"^\d+\s+([a-z0-9_]+)\(", line) or re.match(r"^\d+\s+<\.\.\. ([a-z0-9_]+) resumed>", line)
            if m and m.group(1) in names and "resumed" not in line:
                c[(wl, m.group(1))] += 1
    return c
N = {"clone", "clone3", "execve", "pipe2", "wait4", "rt_sigprocmask", "rt_sigaction"}
sb, sm = syscount(RAW, N), syscount(RAWM, N)
out += ["### Syscall counts for W1/W2/W4 runs, baseline vs patched (strace, all processes)", "",
        "| Workload | Syscall | Baseline | Patched | Δ |", "|---|---|---|---|---|"]
for w, n in sorted({k for k in list(sm)}):
    b, m = sb.get((w, n), 0), sm.get((w, n), 0)
    out.append(f"| {w} | {n} | {b} | {m} | {m - b:+d} |")
out.append("")
os.makedirs(RESM, exist_ok=True)
open(os.path.join(RESM, "m4-compare.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
