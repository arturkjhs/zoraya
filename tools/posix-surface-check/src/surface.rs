//! The tier list and the checks of `libc.a` against it.
//!
//! The list (`docs/adr/posix-surface-T1.txt`) is generated from
//! `docs/research/task-02/libc-surface.csv` by ADR-0100 item 7's rule: the rows
//! of tier `T0` and `T1`, minus `setuid` and `setgid` (ADR-0005), minus
//! `dlopen`, `dlsym`, `dlclose` and `dlerror` (ADR-0100 item 8), plus `writev`
//! (ADR-0005): 248 - 2 - 4 + 1 = 243 names.

use std::collections::{BTreeMap, BTreeSet};

use crate::elf::Object;

/// Tiers whose rows make up the list.
pub const TIERS: [&str; 2] = ["T0", "T1"];
/// Rows struck from the list.
pub const STRUCK: [&str; 6] = ["setuid", "setgid", "dlopen", "dlsym", "dlclose", "dlerror"];
/// Rows added to the list.
pub const ADDED: [&str; 1] = ["writev"];
/// INV-0005-2's exclusion table: no export may have these names. `socket`
/// and `getaddrinfo` are no longer in it: ADR-0225 item 1 (accepted) takes
/// them off, and they are exported only if the tier list or an ADR's
/// `posix-surface-added` block names them (ADR-0287).
pub const DENIED: [&str; 14] = [
    "ptrace",
    "msgget",
    "semget",
    "shmget",
    "pthread_create",
    "dlopen",
    "flock",
    "setuid",
    "setgid",
    "setresuid",
    "setresgid",
    "sigaltstack",
    "setitimer",
    "alarm",
];
/// INV-0005-2's `epoll_*`.
pub const DENIED_PREFIX: &str = "epoll_";
/// The prefix the build gives a name it hides (ADR-0141).
pub const HIDDEN_PREFIX: &str = "__zoraya_";

/// Splits RFC 4180 CSV: fields separated by commas, a quoted field may hold
/// commas and doubled quotes. Every row must have as many fields as the
/// header.
pub fn parse_csv(text: &str) -> Result<Vec<Vec<String>>, String> {
    let mut rows = Vec::new();
    for (n, line) in text.lines().enumerate() {
        if line.is_empty() {
            continue;
        }
        let mut fields = Vec::new();
        let mut field = String::new();
        let mut quoted = false;
        let mut chars = line.chars().peekable();
        while let Some(c) = chars.next() {
            match (quoted, c) {
                (true, '"') if chars.peek() == Some(&'"') => {
                    chars.next();
                    field.push('"');
                }
                (true, '"') => quoted = false,
                (false, '"') if field.is_empty() => quoted = true,
                (false, ',') => fields.push(std::mem::take(&mut field)),
                (_, c) => field.push(c),
            }
        }
        if quoted {
            return Err(format!("line {}: unterminated quote", n + 1));
        }
        fields.push(field);
        rows.push(fields);
    }
    let width = rows.first().map(Vec::len).ok_or("empty CSV")?;
    if let Some(i) = rows.iter().position(|r| r.len() != width) {
        return Err(format!(
            "row {} has {} fields, the header {width}",
            i + 1,
            rows[i].len()
        ));
    }
    Ok(rows)
}

/// The tier list from the CSV's text, sorted.
pub fn tier_list(csv: &str) -> Result<Vec<String>, String> {
    let rows = parse_csv(csv)?;
    let header = &rows[0];
    let col = |name: &str| {
        header
            .iter()
            .position(|h| h == name)
            .ok_or(format!("the CSV has no '{name}' column"))
    };
    let (symbol, tier) = (col("symbol")?, col("tier")?);
    let mut names = BTreeSet::new();
    for row in &rows[1..] {
        if TIERS.contains(&row[tier].as_str()) && !STRUCK.contains(&row[symbol].as_str()) {
            names.insert(row[symbol].clone());
        }
    }
    for s in STRUCK {
        // A struck name must have been a row: otherwise the rule is stale.
        if !rows[1..]
            .iter()
            .any(|r| r[symbol] == s && TIERS.contains(&r[tier].as_str()))
        {
            return Err(format!("struck name '{s}' is not a T0 or T1 row"));
        }
    }
    for a in ADDED {
        if !names.insert(a.to_string()) {
            return Err(format!("added name '{a}' is already a T0 or T1 row"));
        }
    }
    Ok(names.into_iter().collect())
}

/// The list file's text.
pub fn render_list(names: &[String]) -> String {
    let mut out = String::from(
        "# The POSIX tier list (INV-0005-1, INV-0100-1): every name libc.a may export.\n\
         # Generated by `posix-surface-check list` from docs/research/task-02/libc-surface.csv\n\
         # with ADR-0100 item 7's rule: the T0 and T1 rows, minus setuid and setgid\n\
         # (ADR-0005), minus dlopen, dlsym, dlclose and dlerror (ADR-0100 item 8), plus\n\
         # writev (ADR-0005). Do not edit; `make test-unit` and `make check-ports` fail when it is stale.\n",
    );
    out.push_str(&format!("# {} names.\n", names.len()));
    for n in names {
        out.push_str(n);
        out.push('\n');
    }
    out
}

/// The names of a list file: one per line, `#` starts a comment.
pub fn parse_list(text: &str) -> BTreeSet<String> {
    text.lines()
        .map(|l| l.split('#').next().unwrap_or("").trim())
        .filter(|l| !l.is_empty())
        .map(|l| l.split_whitespace().next().unwrap_or(l).to_string())
        .collect()
}

/// Names that are not exports for INV-0100-1: musl's internals (`_` and `__`)
/// and the functions the system-call shim routes to (`zoraya_posix_*`,
/// ADR-0100 item 2, ADR-0141).
pub fn is_internal(name: &str) -> bool {
    name.starts_with('_') || name.starts_with("zoraya_posix_")
}

/// Whether INV-0005-2 forbids exporting `name`.
pub fn is_denied(name: &str) -> bool {
    DENIED.contains(&name) || name.starts_with(DENIED_PREFIX)
}

/// What the check found. Empty means the archive passes.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct Report {
    /// Exports outside the list (INV-0100-1, INV-0005-1).
    pub extra: Vec<String>,
    /// Exports on the exclusion table (INV-0005-2).
    pub denied: Vec<String>,
    /// Names of the list the archive does not define.
    pub missing: Vec<String>,
    /// Members with `svc` instructions outside the permitted members
    /// (INV-0100-2), with their code offsets.
    pub svc: Vec<(String, Vec<usize>)>,
    /// Strong references no member defines, with a member that makes each.
    pub unresolved: Vec<(String, String)>,
    /// Member names that occur more than once.
    pub duplicates: Vec<String>,
    /// Disagreements between the archive's symbol index, which `zoraya-ar`
    /// wrote with its own ELF reader, and the symbols this tool reads.
    pub index: Vec<String>,
    /// Names with a strong definition in more than one member, with the
    /// members: which one a program gets would depend on the archive's order.
    pub doubly_defined: Vec<(String, Vec<String>)>,
}

impl Report {
    pub fn passed(&self) -> bool {
        *self == Report::default()
    }

    pub fn lines(&self) -> Vec<String> {
        let mut out = Vec::new();
        for n in &self.extra {
            out.push(format!("export outside the tier list (INV-0100-1): {n}"));
        }
        for n in &self.denied {
            out.push(format!("export on the exclusion table (INV-0005-2): {n}"));
        }
        for n in &self.missing {
            out.push(format!("tier list name not defined: {n}"));
        }
        for (m, offs) in &self.svc {
            out.push(format!("svc in {m} at code offsets {offs:?} (INV-0100-2)"));
        }
        for (n, m) in &self.unresolved {
            out.push(format!("undefined in the archive: {n} (referenced by {m})"));
        }
        for m in &self.duplicates {
            out.push(format!("member name occurs more than once: {m}"));
        }
        for (n, ms) in &self.doubly_defined {
            out.push(format!(
                "defined strongly in more than one member: {n} ({})",
                ms.join(", ")
            ));
        }
        for m in &self.index {
            out.push(format!("symbol index: {m}"));
        }
        out
    }
}

/// Checks the objects of an archive against `list`. A member whose name
/// starts with one of `svc_allowed` may contain `svc` (zoraya-rt's object,
/// INV-0100-2). `index` is the archive's symbol index, which must name
/// exactly the defined global symbols.
pub fn check(
    list: &BTreeSet<String>,
    members: &[(String, Object<'_>)],
    svc_allowed: &[String],
    index: Option<&[String]>,
) -> Report {
    let mut report = Report::default();
    let mut defined = BTreeSet::new();
    let mut seen = BTreeSet::new();
    for (name, object) in members {
        if !seen.insert(name.clone()) && !report.duplicates.contains(name) {
            report.duplicates.push(name.clone());
        }
        for s in object.symbols.iter().filter(|s| s.is_defined_global()) {
            defined.insert(s.name.clone());
        }
        let svc = crate::elf::svc_offsets(object);
        if !svc.is_empty() && !svc_allowed.iter().any(|p| name.starts_with(p.as_str())) {
            report.svc.push((name.clone(), svc));
        }
    }
    for n in &defined {
        if is_denied(n) {
            report.denied.push(n.clone());
        }
        if !is_internal(n) && !list.contains(n) {
            report.extra.push(n.clone());
        }
    }
    report.missing = list
        .iter()
        .filter(|n| !defined.contains(*n))
        .cloned()
        .collect();
    let mut unresolved = BTreeMap::new();
    for (name, object) in members {
        for s in object.symbols.iter().filter(|s| s.is_strong_undefined()) {
            if !defined.contains(&s.name) {
                unresolved
                    .entry(s.name.clone())
                    .or_insert_with(|| name.clone());
            }
        }
    }
    report.unresolved = unresolved.into_iter().collect();
    let mut strong: BTreeMap<&str, Vec<String>> = BTreeMap::new();
    for (name, object) in members {
        for s in object.symbols.iter().filter(|s| s.is_strong_definition()) {
            strong
                .entry(s.name.as_str())
                .or_default()
                .push(name.clone());
        }
    }
    report.doubly_defined = strong
        .into_iter()
        .filter(|(_, ms)| ms.len() > 1)
        .map(|(n, ms)| (n.to_string(), ms))
        .collect();
    match index {
        None => report.index.push("the archive has no symbol index".into()),
        Some(names) => {
            let indexed: BTreeSet<&String> = names.iter().collect();
            for n in defined.iter().filter(|n| !indexed.contains(n)) {
                report.index.push(format!("{n} is defined but not indexed"));
            }
            for n in indexed.iter().filter(|n| !defined.contains(**n)) {
                report.index.push(format!("{n} is indexed but not defined"));
            }
        }
    }
    report
}

/// The renames that hide every defined name of `objects` that is neither in
/// the list nor internal, in every object that defines or uses it
/// (ADR-0141): `(old, new)` pairs, sorted. Fails if a new name is already
/// taken.
pub fn hide(
    list: &BTreeSet<String>,
    objects: &[Object<'_>],
) -> Result<Vec<(String, String)>, String> {
    let mut all = BTreeSet::new();
    let mut hidden = BTreeSet::new();
    for o in objects {
        for s in &o.symbols {
            all.insert(s.name.clone());
            if s.is_defined_global() && !is_internal(&s.name) && !list.contains(&s.name) {
                hidden.insert(s.name.clone());
            }
        }
    }
    let mut out = Vec::with_capacity(hidden.len());
    for n in hidden {
        let new = format!("{HIDDEN_PREFIX}{n}");
        if all.contains(&new) {
            return Err(format!("cannot hide {n}: {new} already exists"));
        }
        out.push((n, new));
    }
    Ok(out)
}

/// Checks where the index points (the other half of the index check): each
/// entry must point at the header of a member that defines its name, and
/// each name must be indexed once for each member that defines it. `members`
/// are (header offset, member name, object).
pub fn check_index_offsets(
    entries: &[(usize, String)],
    members: &[(usize, String, Object<'_>)],
) -> Vec<String> {
    let mut out = Vec::new();
    let mut wanted: BTreeMap<(&str, usize), usize> = BTreeMap::new();
    for (offset, _, object) in members {
        for s in object.symbols.iter().filter(|s| s.is_defined_global()) {
            *wanted.entry((s.name.as_str(), *offset)).or_default() += 1;
        }
    }
    let mut seen: BTreeMap<(&str, usize), usize> = BTreeMap::new();
    for (offset, name) in entries {
        match members.iter().find(|(o, _, _)| o == offset) {
            None => out.push(format!(
                "{name} points at offset {offset}, which is no member's header"
            )),
            Some((_, member, _)) if !wanted.contains_key(&(name.as_str(), *offset)) => out.push(
                format!("{name} points at {member}, which does not define it"),
            ),
            Some(_) => *seen.entry((name.as_str(), *offset)).or_default() += 1,
        }
    }
    let indexed: BTreeSet<&str> = entries.iter().map(|(_, n)| n.as_str()).collect();
    for ((name, offset), n) in &wanted {
        let got = seen.get(&(*name, *offset)).copied().unwrap_or(0);
        // A name indexed nowhere is the names-only check's report.
        if got != *n && indexed.contains(name) {
            out.push(format!(
                "{name} is indexed {got} times for the member at {offset}, defined {n} times"
            ));
        }
    }
    out
}

/// The names an ADR adds to the surface (INV-0005-1: "or in an accepted
/// superseding ADR"): the lines of its fenced block with the info string
/// `posix-surface-added`, and whether its status is `accepted`. An ADR with
/// no such block is an error, so that a wrong file is not silently empty.
pub fn added_names(adr: &str) -> Result<(Vec<String>, bool), String> {
    let accepted = adr.lines().any(|l| l.trim() == "- **Status:** accepted");
    let mut lines = adr.lines();
    if !lines.any(|l| l.trim() == "```posix-surface-added") {
        return Err("no posix-surface-added block".into());
    }
    let mut names = Vec::new();
    for l in lines {
        let l = l.trim();
        if l == "```" {
            return Ok((names, accepted));
        }
        if !l.is_empty() {
            names.push(l.to_string());
        }
    }
    Err("unterminated posix-surface-added block".into())
}

/// What a call-logged function's own definition is renamed to (ADR-0110
/// item 7, INV-0005-3): its wrapper takes the name.
pub const REAL_PREFIX: &str = "__zoraya_real_";

/// The bitmap of first calls, one byte a function in the order of
/// [`call_log`], and its length.
pub const CALLS_SYMBOL: &str = "__zoraya_calls";
pub const CALLS_COUNT_SYMBOL: &str = "__zoraya_calls_count";
/// The hash of the bitmap's order ([`list_hash`]), which every process
/// reports, so that a log is decoded only with its own build's list.
pub const CALLS_LIST_SYMBOL: &str = "__zoraya_calls_list";

/// FNV-1a, 64 bits, over the names each followed by a newline: the text of
/// `zoraya-calls.txt`. `tools/posix-stats` computes the same.
pub fn list_hash(names: &[String]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for n in names {
        for &b in n.as_bytes().iter().chain(b"\n") {
            h ^= u64::from(b);
            h = h.wrapping_mul(0x0000_0100_0000_01b3);
        }
    }
    h
}

const STT_FUNC: u8 = 2;

/// The logged functions in the bitmap's order, and the renames of
/// [`call_log`].
pub type CallLog = (Vec<String>, Vec<(String, String)>);

/// The largest offset `strb`'s unsigned immediate takes.
const MAX_CALLS: usize = 4096;

/// The exported functions the call log wraps: every function `objects`
/// define (global or weak) whose name is in `list`, sorted, which is the
/// bitmap's order; and the renames that move their definitions, and every
/// reference among `objects`, to [`REAL_PREFIX`]. A program's calls then reach
/// the wrapper and the library's own calls do not, as TASK-02's interposer saw
/// only calls from outside musl. Data names (`environ`, `stdout`) are not
/// wrapped.
pub fn call_log(list: &BTreeSet<String>, objects: &[Object<'_>]) -> Result<CallLog, String> {
    let mut all = BTreeSet::new();
    let mut functions = BTreeSet::new();
    for o in objects {
        for s in &o.symbols {
            all.insert(s.name.as_str());
            if s.is_defined_global() && s.kind == STT_FUNC && list.contains(&s.name) {
                functions.insert(s.name.clone());
            }
        }
    }
    // The library reads the bitmap (a reference); a definition would clash.
    for taken in [CALLS_SYMBOL, CALLS_COUNT_SYMBOL, CALLS_LIST_SYMBOL] {
        let defined = objects
            .iter()
            .flat_map(|o| o.symbols.iter())
            .any(|s| s.name == taken && s.is_defined_global());
        if defined {
            return Err(format!("cannot log: {taken} is already defined"));
        }
    }
    if functions.len() > MAX_CALLS {
        return Err(format!(
            "{} functions to log, more than {MAX_CALLS}",
            functions.len()
        ));
    }
    let mut renames = Vec::with_capacity(functions.len());
    for n in &functions {
        let real = format!("{REAL_PREFIX}{n}");
        if all.contains(real.as_str()) {
            return Err(format!("cannot log {n}: {real} already exists"));
        }
        renames.push((n.clone(), real));
    }
    Ok((functions.into_iter().collect(), renames))
}

/// The assembly of one wrapper: it sets byte `index` of the bitmap and
/// branches to the real definition with every argument register as it was
/// (x16 and x17 are the intra-procedure scratch registers AAPCS64 gives a
/// veneer), so variadic functions, `setjmp` and `vfork` behave as without it.
pub fn call_log_wrapper(name: &str, index: usize) -> String {
    format!(
        "// Generated by posix-surface-check calllog (ADR-0110 item 7).\n\
         \t.section .text.{name},\"ax\",%progbits\n\
         \t.globl {name}\n\
         \t.type {name}, %function\n\
         \t.p2align 2\n\
         {name}:\n\
         \tadrp x16, {CALLS_SYMBOL}\n\
         \tadd x16, x16, :lo12:{CALLS_SYMBOL}\n\
         \tmov w17, #1\n\
         \tstrb w17, [x16, #{index}]\n\
         \tb {REAL_PREFIX}{name}\n\
         \t.size {name}, . - {name}\n"
    )
}

/// The assembly of the bitmap, `count` bytes of zeros, its length, and the
/// hash of its order.
pub fn call_log_bitmap(count: usize, hash: u64) -> String {
    format!(
        "// Generated by posix-surface-check calllog (ADR-0110 item 7).\n\
         \t.bss\n\
         \t.globl {CALLS_SYMBOL}\n\
         \t.type {CALLS_SYMBOL}, %object\n\
         \t.p2align 3\n\
         {CALLS_SYMBOL}:\n\
         \t.zero {}\n\
         \t.size {CALLS_SYMBOL}, {}\n\
         \t.section .rodata\n\
         \t.globl {CALLS_COUNT_SYMBOL}\n\
         \t.type {CALLS_COUNT_SYMBOL}, %object\n\
         \t.p2align 2\n\
         {CALLS_COUNT_SYMBOL}:\n\
         \t.word {count}\n\
         \t.size {CALLS_COUNT_SYMBOL}, 4\n\
         \t.globl {CALLS_LIST_SYMBOL}\n\
         \t.type {CALLS_LIST_SYMBOL}, %object\n\
         \t.p2align 3\n\
         {CALLS_LIST_SYMBOL}:\n\
         \t.quad {hash:#x}\n\
         \t.size {CALLS_LIST_SYMBOL}, 8\n",
        count.max(1),
        count.max(1)
    )
}
