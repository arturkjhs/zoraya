//! Turns the tour (`docs/tour.md`) into the sessions that play it, on the
//! serial console and in the GUI terminal (TASK-18 step 11, INV-0154-4).
//!
//! Every code block of the tour is a piece of a session, in order. In a
//! block, a line `PROMPT> TEXT` is typed (`~> ls`, `~/project> pwd`); a
//! line `PROMPT>` alone is a prompt with nothing typed; `...> TEXT` is a
//! continuation line. `TEXT<Tab>` presses Tab instead of Enter, and the
//! prompt line after its output, with the same text, is the line drawn
//! again (then cleared). `^C` and `^Z` are those keys, pressed once the
//! program is running; the pager's line is answered with a space. Every
//! other line is output, checked in order.

use std::fmt::Write as _;

/// The greeting a new shell prints.
pub const GREETING: &str = "Type help to begin, or help tour.";
/// The pager's question (ADR-0156 item 5).
pub const PAGER: &str = "-- space: next page, q: quit --";
/// The GUI terminal's width.
pub const COLUMNS: usize = 80;

/// One thing in a session.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Step {
    Greeting,
    /// A prompt; with text, typed and entered (or Tab).
    Prompt {
        prompt: String,
        text: Option<String>,
        tab: bool,
    },
    /// The line drawn again after Tab's list.
    Redraw {
        prompt: String,
        text: String,
    },
    Key(char),
    Pager,
    Out(String),
}

/// `PROMPT>` or `PROMPT> TEXT`: a prompt is `...`, or `~` or `/` and a path
/// without spaces.
fn prompt_line(line: &str) -> Option<(String, Option<String>)> {
    let (prompt, rest) = line.split_once('>')?;
    let is_prompt = prompt == "..."
        || ((prompt.starts_with('~') || prompt.starts_with('/'))
            && !prompt.contains(' ')
            && !prompt.contains(':'));
    if !is_prompt {
        return None;
    }
    match rest {
        "" => Some((prompt.into(), None)),
        r => r.strip_prefix(' ').map(|t| (prompt.into(), Some(t.into()))),
    }
}

/// The code blocks of a Markdown text, in order.
pub fn blocks(markdown: &str) -> Vec<Vec<String>> {
    let mut out = Vec::new();
    let mut current: Option<Vec<String>> = None;
    for line in markdown.lines() {
        if line.starts_with("```") {
            match current.take() {
                Some(b) => out.push(b),
                None => current = Some(Vec::new()),
            }
        } else if let Some(b) = current.as_mut() {
            b.push(line.to_string());
        }
    }
    out
}

/// The steps of one block.
pub fn steps(block: &[String]) -> Vec<Step> {
    let mut out = Vec::new();
    let mut tab: Option<(String, String)> = None;
    for line in block {
        if line == GREETING {
            out.push(Step::Greeting);
            continue;
        }
        if line == PAGER {
            out.push(Step::Pager);
            continue;
        }
        if line == "^C" || line == "^Z" {
            out.push(Step::Key(line.chars().nth(1).unwrap_or('C')));
            continue;
        }
        match prompt_line(line) {
            Some((prompt, Some(text))) if tab.as_ref() == Some(&(prompt.clone(), text.clone())) => {
                tab = None;
                out.push(Step::Redraw { prompt, text });
            }
            Some((prompt, text)) => {
                let (text, is_tab) = match text {
                    Some(t) => match t.strip_suffix("<Tab>") {
                        Some(t) => (Some(t.to_string()), true),
                        None => (Some(t), false),
                    },
                    None => (None, false),
                };
                if is_tab {
                    tab = text.clone().map(|t| (prompt.clone(), t));
                }
                out.push(Step::Prompt {
                    prompt,
                    text,
                    tab: is_tab,
                });
            }
            None => out.push(Step::Out(line.clone())),
        }
    }
    out
}

/// Text for a script's `TEXT` or `KEYS`: backslashes escaped.
fn esc(s: &str) -> String {
    s.replace('\\', "\\\\")
}

/// The serial session (`tools/test-runner`'s script).
pub fn serial(markdown: &str) -> String {
    let mut s = String::from(
        "# Generated by zoraya-tour from docs/tour.md: do not edit; a host test\n\
         # fails when it differs (INV-0154-4). The whole tour on the serial\n\
         # console, on the POSIX image without its session file.\n\
         ! panicked\n! ZORAYA-FAULT\n! -FAIL\n",
    );
    // A prompt already waited for, which the next typed line uses.
    let mut prompt_waited = false;
    let mut after_pager = false;
    // The last thing matched was output: what follows must come right
    // after it (`^`), so that no line is left unchecked.
    let mut after_output = false;
    for block in blocks(markdown) {
        for step in steps(&block) {
            match step {
                Step::Greeting => {
                    let _ = writeln!(s, "< {GREETING}");
                    prompt_waited = false;
                }
                Step::Prompt { prompt, text, tab } => {
                    if !prompt_waited {
                        let op = if after_output { '^' } else { '<' };
                        let _ = writeln!(s, "{op} \\r\\n{prompt}>");
                    }
                    prompt_waited = false;
                    match text {
                        None => prompt_waited = true,
                        Some(t) => {
                            let end = if tab { "\\x09" } else { "\\r" };
                            let _ = writeln!(s, "> {}{end}", esc(&t));
                        }
                    }
                }
                Step::Redraw { prompt, text } => {
                    let _ = writeln!(s, "< {prompt}> {}", esc(&text));
                    // Cleared: the same prompt takes the next line.
                    let _ = writeln!(s, "> \\x15");
                    prompt_waited = true;
                }
                Step::Key(k) => {
                    let code = if k == 'Z' { "\\x1a" } else { "\\x03" };
                    let _ = writeln!(s, "~ 1000 zzz\n> {code}\n< ^{k}");
                }
                Step::Pager => {
                    let _ = writeln!(s, "< {PAGER}\n> \\x20");
                    after_pager = true;
                    continue;
                }
                Step::Out(line) => {
                    if line.trim().is_empty() {
                        continue;
                    }
                    if after_pager {
                        let _ = writeln!(s, "< {}", esc(&line));
                    } else {
                        let op = if after_output { '^' } else { '<' };
                        let _ = writeln!(s, "{op} \\r\\n{}", esc(&line));
                    }
                    after_pager = false;
                    after_output = true;
                    continue;
                }
            }
            after_pager = false;
            after_output = false;
        }
    }
    s
}

/// The rows a text takes in the GUI terminal, trailing spaces dropped.
fn rows(text: &str) -> Vec<String> {
    let chars: Vec<char> = text.chars().collect();
    if chars.is_empty() {
        return vec![String::new()];
    }
    chars
        .chunks(COLUMNS)
        .map(|c| c.iter().collect::<String>().trim_end().to_string())
        .collect()
}

/// The GUI session (`tools/test-runner`'s GUI script). Each line is typed
/// whole and checked as the rows it fills; the screen is
/// cleared (Ctrl-L) before each line typed at a first prompt, so that a
/// line and its output fit the window.
pub fn gui(markdown: &str) -> String {
    let mut s = String::from(
        "# Generated by zoraya-tour from docs/tour.md: do not edit; a host test\n\
         # fails when it differs (INV-0154-4). The whole tour in the GUI\n\
         # terminal; Ctrl-L before each line keeps it and its output on one\n\
         # screen.\n\
         serial init: gui: gpu on its own page\n",
    );
    let mut first_greeting = true;
    let mut prompt_waited = false;
    for block in blocks(markdown) {
        for step in steps(&block) {
            let waited = core::mem::take(&mut prompt_waited);
            match step {
                Step::Greeting => {
                    if !first_greeting {
                        // exit: a new window with a new shell.
                        let _ = writeln!(s, "window");
                    }
                    first_greeting = false;
                    let _ = writeln!(s, "screen {GREETING}");
                }
                Step::Prompt { prompt, text, tab } => {
                    // A prompt is its row with the cursor after it: a line
                    // still running shows its text there, and keys typed
                    // while a program runs are its input.
                    let Some(t) = text else {
                        let _ = writeln!(s, "screen {prompt}> _");
                        prompt_waited = true;
                        continue;
                    };
                    if !waited {
                        let _ = writeln!(s, "screen {prompt}> _");
                    }
                    if prompt != "..." {
                        // The cleared screen before what follows is looked
                        // for, which could match the old one (review K12).
                        let _ = writeln!(s, "chord ctrl l\ntop {prompt}> _");
                    }
                    let _ = writeln!(s, "type {}\nwindow", esc(&t));
                    let line = format!("{prompt}> {t}");
                    let r = rows(&line);
                    let (last, full) = r.split_last().expect("one row at least");
                    for row in full {
                        let _ = writeln!(s, "screen {row}");
                    }
                    let _ = writeln!(s, "prefix {last}");
                    // Its output is looked for from the top: a long one may
                    // have scrolled the typed line away.
                    if tab {
                        let _ = writeln!(s, "key tab\nwindow");
                    } else {
                        let _ = writeln!(s, "type \\r\nwindow");
                    }
                }
                Step::Redraw { prompt, text } => {
                    let _ = writeln!(s, "prefix {prompt}> {text}\nchord ctrl u");
                    prompt_waited = true;
                }
                Step::Key(k) => {
                    let code = if k == 'Z' { "z" } else { "c" };
                    let _ = writeln!(s, "pause 1000\nchord ctrl {code}\nscreen ^{k}");
                }
                Step::Pager => {
                    let _ = writeln!(s, "prefix {PAGER}\nkey spc\nwindow");
                }
                Step::Out(line) => {
                    if line.trim().is_empty() {
                        continue;
                    }
                    for row in rows(&line) {
                        let _ = writeln!(s, "screen {row}");
                    }
                }
            }
        }
    }
    let _ = writeln!(s, "exit");
    s
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tour() -> String {
        std::fs::read_to_string(concat!(env!("CARGO_MANIFEST_DIR"), "/../../docs/tour.md"))
            .expect("docs/tour.md")
    }

    /// INV-0154-4: the committed sessions are exactly what the tour gives,
    /// so neither can change alone.
    #[test]
    fn the_committed_sessions_are_the_tours() {
        let root = concat!(env!("CARGO_MANIFEST_DIR"), "/../../");
        let read = |p: &str| std::fs::read_to_string(format!("{root}{p}")).expect(p);
        let t = tour();
        assert!(
            read("tests/posix/tour.script") == serial(&t),
            "tests/posix/tour.script is not docs/tour.md's: run `make tour-scripts`"
        );
        assert!(
            read("tests/posix/tour-gui.script") == gui(&t),
            "tests/posix/tour-gui.script is not docs/tour.md's: run `make tour-scripts`"
        );
    }

    #[test]
    fn lines_are_read_as_the_tour_means_them() {
        let block: Vec<String> = [
            GREETING,
            "~>",
            "~/project> cp --<Tab>",
            "--force    replace TO if it exists",
            "~/project> cp --",
            "~> spin",
            "^C",
            "...>     cp $file $file.bak",
            PAGER,
            "  hint: to set a variable, type: set x 1",
            "zosh: x=1: not a command",
        ]
        .iter()
        .map(|s| s.to_string())
        .collect();
        let p = |prompt: &str, text: Option<&str>, tab| Step::Prompt {
            prompt: prompt.into(),
            text: text.map(String::from),
            tab,
        };
        assert_eq!(
            steps(&block),
            [
                Step::Greeting,
                p("~", None, false),
                p("~/project", Some("cp --"), true),
                Step::Out("--force    replace TO if it exists".into()),
                Step::Redraw {
                    prompt: "~/project".into(),
                    text: "cp --".into()
                },
                p("~", Some("spin"), false),
                Step::Key('C'),
                p("...", Some("    cp $file $file.bak"), false),
                Step::Pager,
                Step::Out("  hint: to set a variable, type: set x 1".into()),
                Step::Out("zosh: x=1: not a command".into()),
            ]
        );
    }

    #[test]
    fn a_long_line_takes_rows_of_the_terminal() {
        let line = "x".repeat(COLUMNS + 5);
        assert_eq!(rows(&line), ["x".repeat(COLUMNS), "xxxxx".into()]);
        assert_eq!(rows("a  "), ["a"]);
        let s = serial("```\n~> echo a\\b\na\\b\n```\n");
        assert!(s.contains("> echo a\\\\b\\r\n< \\r\\na\\\\b\n"), "{s}");
    }
}

/// One described command, for [`conventions`]: its name and description.
pub struct Described {
    pub name: String,
    pub text: String,
}

/// The descriptions a session of [`conventions`] runs, from the
/// repository at `root`: the builtins, the language's, and the native
/// commands and demonstrations of the ramdisk (ADR-0155 rule 8).
pub fn described(root: &std::path::Path) -> Vec<Described> {
    let mut out = Vec::new();
    for dir in [
        "user/describe/builtins",
        "crates/zoraya-shell/describe",
        "user/describe/commands",
        "user/describe/demos",
    ] {
        let mut files: Vec<_> = std::fs::read_dir(root.join(dir))
            .map(|r| r.flatten().map(|e| e.path()).collect())
            .unwrap_or_default();
        files.sort();
        for f in files {
            if f.extension().and_then(|e| e.to_str()) != Some("cmd") {
                continue;
            }
            let name = f
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("")
                .to_string();
            let text = std::fs::read_to_string(&f).unwrap_or_default();
            out.push(Described { name, text });
        }
    }
    out
}

/// INV-0155-1's session on the serial console, with a volume: every builtin and every
/// command of the ramdisk prints its `--help` exactly as its description
/// renders on the host (`zoraya_command::help`), and exits 0; with an
/// option it does not have it prints the usage error and exits 2.
pub fn conventions(commands: &[Described]) -> Result<String, String> {
    let mut s = String::from(
        "# Generated by zoraya-tour from the descriptions: do not edit; a host\n\
         # test fails when it differs. INV-0155-1: --help as the description\n\
         # renders it, exit 0; an unknown option, the usage error, exit 2.\n\
         ! panicked\n! ZORAYA-FAULT\n\
         < Type help to begin, or help tour.\n< \\r\\n~>\n",
    );
    let status = |s: &mut String, words: &str| {
        let _ = writeln!(s, "> status\\r\n< \\r\\n{words}\n^ \\r\\n~>");
    };
    for c in commands {
        let d =
            zoraya_describe::parse(c.text.as_bytes()).map_err(|e| format!("{}: {e}", c.name))?;
        let lines = |s: &mut String, text: &str| {
            for (i, line) in text.lines().enumerate() {
                let op = if i == 0 { '<' } else { '^' };
                let _ = writeln!(s, "{op} \\r\\n{}", esc(line));
            }
            let _ = writeln!(s, "^ \\r\\n~>");
        };
        let _ = writeln!(s, "> {} --help\\r", c.name);
        lines(&mut s, &zoraya_command::help(&d));
        status(&mut s, "succeeded (exit status 0)");
        let e = match zoraya_command::parse(&d, &["--no-such-option"]) {
            Err(e) => e,
            Ok(_) => return Err(format!("{}: --no-such-option was taken", c.name)),
        };
        let _ = writeln!(s, "> {} --no-such-option\\r", c.name);
        lines(&mut s, &zoraya_command::usage_error(&d, &e));
        status(&mut s, "exit status 2");
    }
    let _ = writeln!(s, "x power off\n> poweroff\\r");
    Ok(s)
}

