/* Generates crates/zoraya-width/src/table.rs from musl's own wcwidth
 * (ADR-0332 item 9): the pinned release's src/ctype/wcwidth.c is compiled for
 * the host and asked for every code point. Built and run by gen.sh. */
#include <stdio.h>
#include <wchar.h>

int musl_wcwidth(wchar_t wc);

int main(int argc, char **argv)
{
	const char *pin = argc > 1 ? argv[1] : "unknown";
	printf("// Generated by tools/term-width/gen.sh from the wcwidth of %s. Do not edit.\n", pin);
	printf("// A run starts at a code point and lasts until the next one's start.\n");
	printf("pub static RUNS: &[(u32, i8)] = &[\n");
	int prev = 99;
	for (unsigned long c = 0; c <= 0x10ffff; c++) {
		int w = musl_wcwidth((wchar_t)c);
		if (w != prev) {
			printf("    (0x%lx, %d),\n", c, w);
			prev = w;
		}
	}
	printf("];\n");
	return 0;
}
